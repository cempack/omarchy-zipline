#!/bin/bash

# Removes what install.sh added: the keybindings file and its require block,
# the menu entries, the CLI link and the bar widget.
#
#   ./uninstall.sh           keep config and upload history
#   ./uninstall.sh --purge   also delete ~/.config/omarchy-zipline and history
#
# The plugin files themselves go with: omarchy plugin remove io.github.cempack.zipline

set -euo pipefail

PLUGIN_ID="io.github.cempack.zipline"
HYPR_DIR="$HOME/.config/hypr"
BINDINGS_FILE="$HYPR_DIR/bindings.lua"
ZIPLINE_LUA="$HYPR_DIR/zipline.lua"
MENU_FILE="$HOME/.config/omarchy/extensions/omarchy-menu.jsonc"
BIN_LINK="$HOME/.local/bin/omarchy-zipline"
CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/omarchy-zipline"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/omarchy-zipline"
MARK_BEGIN="omarchy-zipline >>>"
MARK_END="<<< omarchy-zipline"

PURGE=0
for arg in "$@"; do
  case $arg in
    --purge) PURGE=1 ;;
    -h | --help)
      sed -n '3,9p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *)
      echo "uninstall.sh: unknown option: $arg" >&2
      exit 1
      ;;
  esac
done

say() { printf '  %s\n' "$*"; }

remove_block() {
  # remove_block <file>: drop the marked block (and the blank line before it).
  local file=$1
  [[ -f $file ]] && grep -q "$MARK_BEGIN" "$file" || return 0
  cp -p "$file" "$file.bak.$(date +%s)"
  python3 -I - "$file" "$MARK_BEGIN" "$MARK_END" <<'PY'
import re, sys
path, begin, end = sys.argv[1:4]
text = open(path, encoding="utf-8").read()
pattern = r"(?:\n[ \t]*(?=\n))?\n?[ \t]*(?:--|//) " + re.escape(begin) + r"[^\n]*\n.*?[ \t]*(?:--|//) " + re.escape(end) + r"[^\n]*"
text = re.sub(pattern, "", text, flags=re.S)
open(path, "w", encoding="utf-8").write(text)
PY
  say "Cleaned $file"
}

echo "Removing Zipline integration"

remove_block "$BINDINGS_FILE"
if [[ -f $ZIPLINE_LUA ]] && grep -q "Generated by omarchy-zipline" "$ZIPLINE_LUA"; then
  rm -f "$ZIPLINE_LUA"
  say "Removed $ZIPLINE_LUA"
fi
remove_block "$MENU_FILE"

if [[ -L $BIN_LINK ]]; then
  rm -f "$BIN_LINK"
  say "Removed $BIN_LINK"
fi

if command -v omarchy >/dev/null 2>&1 && omarchy-shell shell ping >/dev/null 2>&1; then
  omarchy plugin disable "$PLUGIN_ID" >/dev/null 2>&1 && say "Removed the bar widget" || true
fi

if command -v hyprctl >/dev/null 2>&1 && [[ -n ${HYPRLAND_INSTANCE_SIGNATURE:-} ]]; then
  hyprctl reload >/dev/null 2>&1 || true
fi

if ((PURGE)); then
  rm -rf "$CONFIG_DIR" "$STATE_DIR"
  say "Deleted $CONFIG_DIR and $STATE_DIR"
else
  say "Kept $CONFIG_DIR (token) and $STATE_DIR (history); --purge deletes them"
fi

echo
echo "Done. To delete the plugin files too: omarchy plugin remove $PLUGIN_ID"
